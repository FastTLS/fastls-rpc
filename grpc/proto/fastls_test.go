func TestFetchRequestDescriptorAndRoundTrip(t *testing.T) {
	request := &FetchRequest{
		Url:                 "https://example.com/",
		Method:              "GET",
		Browser:             "chrome",
		Http2SettingsString: "1:65536;2:0;4:6291456;6:262144|15663105|0|m,a,s,p",
		ParentProxy:         "http://127.0.0.1:8080",
	}

	descriptor := request.ProtoReflect().Descriptor()
	for name, number := range map[string]int32{
		"url":                   1,
		"http2_settings_string": 12,
		"parent_proxy":          13,
		"include_body_base64":   15,
	} {
		field := descriptor.Fields().ByName(protoreflect.Name(name))
		if field == nil {
			t.Fatalf("field %q is missing from the generated descriptor", name)
		}
		if got := int32(field.Number()); got != number {
			t.Fatalf("field %q number = %d, want %d", name, got, number)
		}
	}

	encoded, err := proto.Marshal(request)
	if err != nil {
		t.Fatalf("marshal FetchRequest: %v", err)
	}

	var decoded FetchRequest
	if err := proto.Unmarshal(encoded, &decoded); err != nil {
		t.Fatalf("unmarshal FetchRequest: %v", err)
	}
	if !proto.Equal(request, &decoded) {
		t.Fatalf("round trip mismatch: got %v, want %v", &decoded, request)
	}
}

func TestCheckedInPythonDescriptorIncludesCurrentFields(t *testing.T) {
	generatedPath := filepath.Join("..", "grpc_example", "fastls_pb2.py")
	contents, err := os.ReadFile(generatedPath)
	if err != nil {
		t.Fatal(err)
	}
	// Python's generated byte literal may hex-escape letters (for example
	// body_base64 begins with \x62); inspect the decoded names, not its spelling.
	decodedNames := regexp.MustCompile(`\\x[0-9a-fA-F]{2}`).ReplaceAllStringFunc(string(contents), func(escape string) string { value, _ := hex.DecodeString(escape[2:]); return string(value) })
	for _, field := range []string{"http2_settings_string", "parent_proxy", "header_values", "body_base64", "error_code", "timeout_phase"} {
		if !strings.Contains(decodedNames, field) {
			t.Fatalf("%s is missing %q; regenerate Python protobuf files", generatedPath, field)
		}
	}
}

func TestResponseContractFieldsRoundTrip(t *testing.T) {
	original := &FetchResponse{Ok: true, BodyBase64: "AP+A", HeaderValues: map[string]*HeaderValues{"Set-Cookie": {Values: []string{"a=1", "b=2"}}}, ErrorCode: "timeout", TimeoutPhase: "total"}
	encoded, err := proto.Marshal(original)
	if err != nil {
		t.Fatal(err)
	}
	var decoded FetchResponse
	if err = proto.Unmarshal(encoded, &decoded); err != nil || !proto.Equal(original, &decoded) {
		t.Fatalf("response round trip: %v %+v", err, &decoded)
	}
	for name, number := range map[string]protoreflect.FieldNumber{"header_values": 9, "body_base64": 10, "error_code": 11, "timeout_phase": 12} {
		field := original.ProtoReflect().Descriptor().Fields().ByName(protoreflect.Name(name))
		if field == nil || field.Number() != number {
			t.Fatalf("descriptor field %s changed", name)
		}
	}
}
